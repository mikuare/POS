-- Fix Supabase linter warning: function_search_path_mutable
-- Trigger helper functions should use an explicit search_path.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

